# Constructing the phylogenies 
# convert alignment to ape-format
library(ape)

# Convert to ape-compatible DNAbin
dna <- as.DNAbin(alignment)

# Inspect alignment
print(dna)

# Evolutionary distances
distances <- dist.dna(
  dna,
  model = "JC",
  pairwise.deletion = FALSE
)

print(as.matrix(distances))

# Create a Neighbor-Joining tree
tree_nj <- nj(distances)

# Plot
plot(
  tree_nj,
  main = "Neighbor-Joining phylogeny",
  cex = 1.2
)
add.scale.bar()


# Create a Maximum-Likelihood tree
library(phangorn)

# Convert DNAbin to phyDat (phylip format)
phy_data <- phyDat(dna, type = "DNA")

# Initialize ML using NJ topology
fit <- pml(tree_nj, data = phy_data)

# Optimize likelihood
fit_ml <- optim.pml(
  fit,
  model = "K80",
  optNni = TRUE,
  optBf = FALSE,
  optQ = FALSE,
  optGamma = FALSE,
  optInv = FALSE
)

# Extract tree
tree_ml <- fit_ml$tree

plot(
  tree_ml,
  main = "Maximum-Likelihood phylogeny",
  cex = 1.2
)
add.scale.bar()



# compare NJ and ML trees

par(mfrow = c(1, 2))

plot(tree_nj, main = "Neighbor Joining")
add.scale.bar()

plot(tree_ml, main = "Maximum Likelihood")
add.scale.bar()

